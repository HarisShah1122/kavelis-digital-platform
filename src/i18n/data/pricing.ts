/** Plans, request-system steps, and pricing FAQs in the active language. */
export function usePricing() {
  const { lang } = useI18n()
  return useMemo(
    () => ({
      plans: localizeItems(subscriptionPlans, plansAr, lang),
      steps: requestSystemSteps.map((step) => (lang === 'ar' ? { ...step, ...stepsAr[step.id] } : step)),
      faqs: localizeItems(pricingFaqs, faqsAr, lang),
    }),
    [lang],
  )
}
