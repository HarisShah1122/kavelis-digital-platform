/** Catalogue products, categories, and internal products in the active language. */
export function useMarketplace() {
  const { lang } = useI18n()
  return useMemo(() => {
    const products = localizeItems(marketplaceProducts, productsAr, lang)
    const categories = localizeItems(marketplaceCategories, categoriesAr, lang)
    return {
      products,
      categories,
      internal: localizeItems(internalProducts, internalAr, lang),
      getProduct: (id: string) => products.find((product) => product.id === id),
      getCategory: (id: string) => categories.find((category) => category.id === id),
    }
  }, [lang])
}
